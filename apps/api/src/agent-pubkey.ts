import { fromHex } from '@agenttrace/manifest'
import { PublicKey } from '@solana/web3.js'
import { AppError } from './errors.js'

/**
 * Хекс потрібної довжини ще не означає ключ: більш ніж половина 32-байтових
 * рядків не є точкою кривої ed25519 взагалі (заміряно: 90 на кривій із 200
 * випадкових). Підпис таким ключем не перевіриться ніколи — і дорого тут не
 * саме відхилення, а те, **де** воно станеться, якщо не перевірити зараз:
 * рішення пройде приймання, ляже в базу підписаним, і publisher витратить на
 * нього всі десять спроб публікації, після яких рядок назавжди стане `failed`.
 *
 * Тому місце перевірки — приймання, тобто той єдиний ендпоінт, де ключ
 * називають уперше (`PLAN.md`, «Межі й валідація»). Далі його вже не приймають,
 * а знаходять: `POST /v1/decisions` шукає **зареєстрований** ключ і невідомий
 * відхиляє.
 *
 * У Zod-схемі `packages/shared` цього немає навмисно: схему імпортують і SDK,
 * і браузер, а перевірка точки притягнула б туди бібліотеку ланцюга заради
 * 32 байтів. Ціна рішення — SDK дізнається про поганий ключ від API, а не
 * локально; вона мала, бо SDK свої ключі генерує сам і випадкових не шле.
 */
function isOnCurve(publicKey: string): boolean {
  try {
    return PublicKey.isOnCurve(fromHex(publicKey))
  } catch {
    // Довжину й алфавіт уже перевірила схема, тож сюди можна дійти лише
    // майбутньою зміною межі. Виняток на цій гілці означав би 500 на
    // поганому вводі — ціле призначення цієї функції навпаки.
    return false
  }
}

/**
 * Чого перевірка **не** доводить: що приватний ключ узагалі хтось тримає.
 * Реєстрація цього не доводить ніяк — вона довіряє ingest-ключу проєкту, і
 * власність ключа підтверджує вже перше рішення, підписане ним. Тут
 * відсіюється лише те, що ключем не могло бути.
 */
export function assertAgentPubkeyUsable(publicKey: string): void {
  if (isOnCurve(publicKey)) return
  throw new AppError(
    'INVALID_INPUT',
    'This public key is not a point on the ed25519 curve, so nothing could ever sign with it',
  )
}
